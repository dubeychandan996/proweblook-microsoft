/**
 * Bundles excel-addin/* text assets into src/generated-static.js so the Cloudflare
 * Edge Worker serves byte-identical copies of manifest.xml, functions.json, functions.js,
 * taskpane.html, taskpane.css, and taskpane.js.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const files = [
	'manifest.xml',
	'functions.json',
	'functions.js',
	'taskpane.html',
	'taskpane.css',
	'taskpane.js',
];

const staticMap = {};
for (const f of files) {
	staticMap[f] = fs.readFileSync(path.join(ROOT, 'excel-addin', f), 'utf8');
}

const out = `// Auto-generated by scripts/bundle-static.mjs — do not edit manually.\nexport const EXCEL_STATIC_FILES = ${JSON.stringify(staticMap, null, '\t')};\n`;
fs.writeFileSync(path.join(ROOT, 'src', 'generated-static.js'), out);
console.log('Bundled Excel static files into src/generated-static.js');
